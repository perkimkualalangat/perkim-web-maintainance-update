/* ---------- Keadaan ---------- */

let currentLang = DEFAULT_LANG;

function storageAvailable() {
  return typeof globalThis.localStorage !== 'undefined' && globalThis.localStorage !== null;
}

function interpolate(text, vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
  ));
}

/* ---------- API ---------- */

/**
 * Terjemah kunci label UI.
 * @param {string} key
 * @param {Record<string, unknown>} [vars] - interpolasi {nama}
 * @returns {string}
 */
export function t(key, vars) {
  const table = MESSAGES[currentLang] || MESSAGES[DEFAULT_LANG];
  const text = table[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  return interpolate(text, vars);
}

/**
 * Tukar bahasa UI. Nilai sah: 'ms' (BM) | 'en'.
 * @param {'ms'|'en'} lang
 */
export function setLang(lang) {
  if (!LANGS.includes(lang)) {
    console.warn(`[i18n] Bahasa tidak disokong: ${lang}`);
    return currentLang;
  }
  currentLang = lang;
  if (storageAvailable()) {
    try { globalThis.localStorage.setItem(STORAGE_KEY, lang); } catch { /* abaikan */ }
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang === 'ms' ? 'ms' : 'en';
  }
  events.emit('i18n:changed', { lang });
  return currentLang;
}

/** Bahasa semasa. */
export function getLang() {
  return currentLang;
}

/** Muat bahasa tersimpan (dipanggil semasa boot). */
export function init() {
  if (storageAvailable()) {
    try {
      const saved = globalThis.localStorage.getItem(STORAGE_KEY);
      if (LANGS.includes(saved)) currentLang = saved;
    } catch { /* abaikan */ }
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = currentLang === 'ms' ? 'ms' : 'en';
  }
  return currentLang;
}

/** Senarai bahasa yang disokong. */
export function listLangs() {
  return [...LANGS];
}

